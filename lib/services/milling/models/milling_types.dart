/// Перепрофилирование края под фрезу — типы и константы.
///
/// ВАЖНО про систему координат: как и везде в приложении, работаем в
/// ОТСЧЁТАХ ПО РЕЙКЕ (мм): больше число = ниже точка. Это отличается от
/// исходного Road Designer (там прямая СИ в метрах), но позволяет не
/// конвертировать данные туда-сюда и переиспользовать привычный ввод.
///
/// Следствия для формул:
///  - срез (фреза) = P − F  (проект ниже факта ⇒ отсчёт больше)
///  - водораздел = САМАЯ ВЫСОКАЯ точка ⇒ наименьший отсчёт; от него
///    отсчёт РАСТЁТ в обе стороны
///  - отметка после укладки = P − overlay (уложили слой ⇒ стало выше)
class MillingTypes {
  /// Минимальный продольный уклон, мм/м (‰)
  static const double kMin = 3.0;

  /// Шаг перебора отметок, мм
  static const int delta = 5;

  /// Толщина укладки (один слой), мм. К срезу не относится — прибавляется
  /// после расчёта, к итоговой проектной отметке.
  static const double overlay = 50.0;

  /// Целевой срез, мм. Стремимся именно К НЕМУ, а не к минимуму:
  /// иногда специально режут глубже, к 0 идут только в крайнем случае.
  static const double targetCut = 50.0;

  /// Ширина зоны перестраховки над kMin, ‰. В пределах [kMin, kMin+margin]
  /// небольшой штраф, выше — ровно ноль (дальше решает только срез).
  static const double slopeSafeMargin = 0.5;

  /// Штраф за уклон в зоне перестраховки. Соизмерим с остальными
  /// слагаемыми: типичный балл участка 2-6, а отклонения среза дают
  /// единицы баллов. Прежние 50 весили в 20 раз больше всего остального
  /// и вынуждали солвер покупать запас по уклону любой ценой по срезу.
  /// Уровень тот же, что у первой зоны в дренаже.
  static const double slopePenaltyNear = 10.0;

  /// Поперечный уклон ось→край в точке водораздела: край не может быть
  /// выше оси. 0‰ — норма, до этого предела допускается в крайнем случае.
  static const double crossSlopeHardFloor = -2.0; // ‰
  /// Та же шкала, что и у штрафа за уклон — иначе один отрицательный
  /// поперечник в водоразделе перевешивал весь остальной расчёт.
  static const double crossSlopePenaltyNear = 10.0;

  /// Допуски среза по типам точек, мм: [min, max].
  static const Map<String, List<int>> tolerance = {
    'DK': [35, 70],
    'O':  [0, 70],
    'WD': [0, 50],
    // Примыкание: срез ровно в толщину укладки — новое покрытие должно
    // лечь заподлицо с существующим, без ступеньки.
    'PR': [50, 50],
  };

  /// Допустимое оголение борта (Z_борт − Z_проект_после_укладки), мм —
  /// единый диапазон для всех точек, где борт введён. Жёсткое
  /// ограничение: сужает коридор с ОБЕИХ сторон, а не штрафует.
  /// Снизу — чтобы вода не переливалась через борт, сверху — чтобы не
  /// разуло основание бортового камня.
  static const double bortExposureMin = 100.0;
  static const double bortExposureMax = 270.0;

  /// Типы точек, которые пользователь вводит сам (WD назначает солвер).
  static const List<String> inputTypes = ['O', 'DK', 'PR'];

  /// Шаг поиска позиции виртуального водораздела внутри сегмента, м.
  static const double watershedPositionStep = 1.0;

  /// Зона равенства баллов при выборе позиции водораздела. Если два
  /// варианта различаются меньше чем на это значение, выбирается тот, что
  /// ближе к физически высшей точке края, а не тот, где формально на
  /// сотую доли балла лучше.
  static const double watershedTieScore = 1.0;
}
